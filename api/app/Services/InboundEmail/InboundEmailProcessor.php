<?php

namespace App\Services\InboundEmail;

use App\Actions\Ticket\CreateTicketAction;
use App\Actions\Ticket\CreateTicketMessageAction;
use App\Actions\Ticket\ReopenTicketAction;
use App\Actions\Ticket\UploadTicketAttachmentAction;
use App\Enums\TicketMessageType;
use App\Exceptions\PlanLimitExceededException;
use App\Models\Customer;
use App\Models\InboundEmail;
use App\Models\Tenant;
use App\Models\Ticket;
use App\Models\TicketMessage;
use App\Models\User;
use App\Services\PlanLimitService;
use App\Services\TicketStatusWorkflow;
use App\Support\AttachmentRules;
use App\Support\TenantContext;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Validator;
use Illuminate\Support\Str;

/**
 * Turns one email delivered by Mailgun into a ticket, or a reply on an existing
 * ticket. Every outcome is recorded in inbound_emails so an administrator can see
 * what happened to each message, including the ones that were deliberately skipped.
 */
class InboundEmailProcessor
{
    private const MAX_BODY = 20000;

    public function __construct(
        private TenantContext $tenantContext,
        private CreateTicketAction $createTicket,
        private CreateTicketMessageAction $createMessage,
        private ReopenTicketAction $reopenTicket,
        private UploadTicketAttachmentAction $uploadAttachment,
        private PlanLimitService $planLimits,
    ) {}

    /**
     * @param  array<string, mixed>  $fields  the form fields Mailgun posted
     * @param  array<int|string, UploadedFile>  $files  the attachments, in order
     * @return InboundEmail|null null when the recipient is not one of our workspace addresses
     */
    public function process(array $fields, array $files): ?InboundEmail
    {
        $recipient = strtolower(trim((string) ($fields['recipient'] ?? '')));
        $tenant = InboundEmailSettings::tenantForRecipient($recipient);

        if (! $tenant) {
            return null;
        }

        return $this->tenantContext->runAs($tenant, fn () => $this->processForTenant($tenant, $recipient, $fields, $files));
    }

    private function processForTenant(Tenant $tenant, string $recipient, array $fields, array $files): InboundEmail
    {
        [$fromEmail, $fromName] = $this->parseSender($fields);
        $messageId = $this->cleanMessageId($fields['Message-Id'] ?? $fields['Message-ID'] ?? $fields['message-id'] ?? null);

        $record = $this->claim($tenant, $messageId, [
            'from_email' => $fromEmail ?: 'unknown',
            'from_name' => $fromName,
            'subject' => Str::limit(trim((string) ($fields['subject'] ?? '')), 250, ''),
            'recipient' => $recipient,
        ]);

        if ($record->status !== InboundEmail::PROCESSING) {
            return $record; // a retry of a message that was already handled
        }

        try {
            [$status, $ticketId, $note] = $this->decide($tenant, $fields, $files, $fromEmail, $fromName, $record);
        } catch (\Throwable $e) {
            report($e);
            $record->update(['status' => InboundEmail::FAILED, 'note' => Str::limit($e->getMessage(), 500)]);

            throw $e; // 5xx so Mailgun retries; claim() lets a failed row be processed again
        }

        $record->update(['status' => $status, 'ticket_id' => $ticketId, 'note' => $note ?: $record->note]);

        return $record;
    }

    /**
     * @return array{0: string, 1: ?string, 2: ?string} status, ticket id, note
     */
    private function decide(Tenant $tenant, array $fields, array $files, string $fromEmail, ?string $fromName, InboundEmail $record): array
    {
        if (! $tenant->isActive() || ! InboundEmailSettings::enabled($tenant)) {
            return ['rejected_disabled', null, 'Email-to-ticket is switched off for this workspace.'];
        }

        if (! filter_var($fromEmail, FILTER_VALIDATE_EMAIL)) {
            return ['rejected_bad_sender', null, 'The sender address is not valid.'];
        }

        if ($reason = $this->autoGeneratedReason($fields, $fromEmail, $tenant)) {
            return ['ignored_auto_generated', null, $reason];
        }

        $user = User::where('email', $fromEmail)->first();

        if ($user && ! $user->hasRole('Customer')) {
            return ['ignored_staff_sender', null, 'The sender is a team member; emails from staff are not turned into tickets.'];
        }

        if (! $user) {
            if (! InboundEmailSettings::createsCustomers($tenant)) {
                return ['rejected_unknown_sender', null, 'The sender is not a customer of this workspace.'];
            }

            try {
                $this->planLimits->assertCanCreate($tenant, 'customers');
            } catch (PlanLimitExceededException $e) {
                return ['rejected_plan_limit', null, $e->getMessage()];
            }

            $user = $this->createCustomerUser($fromEmail, $fromName);
        }

        $customer = Customer::where('user_id', $user->id)->first()
            ?? Customer::create(['user_id' => $user->id, 'customer_type' => 'individual']);

        $ticket = $this->findThread($fields, $user);

        if ($ticket && ! $ticket->status->is_closed) {
            return $this->addReply($ticket, $user, $fields, $files, $record);
        }

        try {
            $this->planLimits->assertCanCreate($tenant, 'tickets_per_month');
        } catch (PlanLimitExceededException $e) {
            return ['rejected_plan_limit', null, $e->getMessage()];
        }

        return $this->openTicket($customer, $user, $fields, $files, $record, $ticket);
    }

    private function openTicket(Customer $customer, User $user, array $fields, array $files, InboundEmail $record, ?Ticket $closedTicket): array
    {
        $subject = trim((string) ($fields['subject'] ?? ''));
        $body = $this->bodyOf($fields, preferStripped: false);

        if ($closedTicket) {
            $body = "Follow-up to closed ticket {$closedTicket->ticket_number}.\n\n".$body;
        }

        $ticket = $this->createTicket->execute($customer, [
            'subject' => Str::limit($subject !== '' ? $subject : '(no subject)', 250, ''),
            'description' => $body,
        ]);

        [$saved, $skipped] = $this->saveAttachments($ticket, $user, $files, null);
        $record->update(['attachments_saved' => $saved, 'attachments_skipped' => $skipped]);

        return [InboundEmail::TICKET_CREATED, $ticket->id, $skipped ? "{$skipped} attachment(s) were skipped (type or size not allowed)." : null];
    }

    private function addReply(Ticket $ticket, User $user, array $fields, array $files, InboundEmail $record): array
    {
        $message = $this->createMessage->execute(
            $ticket,
            $user,
            TicketMessageType::CustomerMessage,
            $this->bodyOf($fields, preferStripped: true),
        );

        if ($ticket->status->slug === TicketStatusWorkflow::RESOLVED) {
            $this->reopenTicket->execute($ticket, $user, 'The customer replied by email.');
        }

        [$saved, $skipped] = $this->saveAttachments($ticket, $user, $files, $message);
        $record->update(['attachments_saved' => $saved, 'attachments_skipped' => $skipped]);

        return [InboundEmail::REPLY_ADDED, $ticket->id, $skipped ? "{$skipped} attachment(s) were skipped (type or size not allowed)." : null];
    }

    /**
     * Finds the ticket this email continues: first through the Message-IDs it
     * answers, then through a ticket number in the subject. Either way the sender
     * must be that ticket's own customer, so a stranger who guesses a ticket
     * number cannot write into someone else's conversation.
     */
    private function findThread(array $fields, User $sender): ?Ticket
    {
        $ticket = null;

        $referenced = $this->referencedMessageIds($fields);
        if ($referenced !== []) {
            $ticketId = InboundEmail::whereIn('message_id', $referenced)->whereNotNull('ticket_id')->orderByDesc('id')->value('ticket_id');
            $ticket = $ticketId ? Ticket::with(['status', 'customer'])->find($ticketId) : null;
        }

        if (! $ticket) {
            preg_match_all('/[A-Za-z0-9]+(?:-[A-Za-z0-9]+)+/', (string) ($fields['subject'] ?? ''), $matches);
            $candidates = array_values(array_unique(array_merge($matches[0], array_map('strtoupper', $matches[0]))));

            if ($candidates !== []) {
                $ticket = Ticket::with(['status', 'customer'])->whereIn('ticket_number', $candidates)->orderByDesc('id')->first();
            }
        }

        return $ticket && $ticket->customer?->user_id === $sender->id ? $ticket : null;
    }

    /** @return array{0: int, 1: int} saved, skipped */
    private function saveAttachments(Ticket $ticket, User $uploader, array $files, ?TicketMessage $message): array
    {
        $saved = 0;
        $skipped = 0;

        foreach ($files as $file) {
            $valid = $file instanceof UploadedFile
                && $saved < config('attachments.max_per_message')
                && Validator::make(['file' => $file], ['file' => AttachmentRules::file()])->passes();

            if (! $valid) {
                $skipped++;

                continue;
            }

            $this->uploadAttachment->execute($ticket, $file, $uploader, $message);
            $saved++;
        }

        return [$saved, $skipped];
    }

    private function createCustomerUser(string $email, ?string $name): User
    {
        return DB::transaction(function () use ($email, $name) {
            $user = User::create([
                'name' => $name ?: Str::before($email, '@'),
                'email' => $email,
                // Nobody knows this: the customer sets their own through "forgot password" if they ever want to sign in.
                'password' => Hash::make(Str::random(40)),
                'is_active' => true,
            ]);
            $user->assignRole('Customer');

            return $user;
        });
    }

    /**
     * Records the message before doing anything with it. The unique (tenant, message_id)
     * index makes a retry of the same email a no-op, while a row that previously failed
     * is taken over and processed again.
     */
    private function claim(Tenant $tenant, ?string $messageId, array $attributes): InboundEmail
    {
        try {
            return InboundEmail::create($attributes + ['message_id' => $messageId, 'status' => InboundEmail::PROCESSING]);
        } catch (UniqueConstraintViolationException) {
            $existing = InboundEmail::where('message_id', $messageId)->firstOrFail();

            if ($existing->status === InboundEmail::FAILED) {
                $existing->update(['status' => InboundEmail::PROCESSING, 'note' => null]);
            }

            return $existing;
        }
    }

    /** @return array{0: string, 1: ?string} email, display name */
    private function parseSender(array $fields): array
    {
        $from = trim((string) ($fields['from'] ?? ''));
        $name = null;
        $email = '';

        if (preg_match('/^\s*"?([^"<]*?)"?\s*<([^>]+)>\s*$/', $from, $m)) {
            $name = trim($m[1]) !== '' ? trim($m[1]) : null;
            $email = $m[2];
        } elseif ($from !== '') {
            $email = $from;
        }

        if (! filter_var($email, FILTER_VALIDATE_EMAIL)) {
            $email = (string) ($fields['sender'] ?? $email);
        }

        return [strtolower(trim($email)), $name ? Str::limit($name, 250, '') : null];
    }

    private function cleanMessageId(mixed $value): ?string
    {
        $id = trim((string) $value, " \t\n\r\0\x0B<>");

        return $id !== '' ? Str::limit($id, 250, '') : null;
    }

    /** @return string[] */
    private function referencedMessageIds(array $fields): array
    {
        $raw = trim(($fields['In-Reply-To'] ?? '').' '.($fields['References'] ?? ''));
        preg_match_all('/<([^>]+)>/', $raw, $matches);

        return array_values(array_unique($matches[1]));
    }

    /**
     * Text of the email. For a reply the provider's "stripped" version (quoted history
     * and signature removed) keeps the thread readable; for a new ticket the full text
     * is kept. An HTML-only email is flattened to text.
     */
    private function bodyOf(array $fields, bool $preferStripped): string
    {
        $text = $preferStripped
            ? ($fields['stripped-text'] ?? $fields['body-plain'] ?? '')
            : ($fields['body-plain'] ?? $fields['stripped-text'] ?? '');

        if (trim((string) $text) === '') {
            $html = (string) ($fields['stripped-html'] ?? $fields['body-html'] ?? '');
            $html = preg_replace(['/<br\s*\/?>/i', '/<\/(div|li|tr)>/i', '/<\/p>/i'], ["\n", "\n", "\n\n"], $html);
            $text = preg_replace("/\n{3,}/", "\n\n", html_entity_decode(strip_tags($html), ENT_QUOTES | ENT_HTML5));
        }

        $text = trim(preg_replace("/\r\n?/", "\n", (string) $text));

        return $text === '' ? '(no message text)' : Str::limit($text, self::MAX_BODY, '');
    }

    /** Why this looks like a robot (auto-reply, bounce, list mail), or null if it looks human. */
    private function autoGeneratedReason(array $fields, string $fromEmail, Tenant $tenant): ?string
    {
        $headers = [];
        foreach ((array) json_decode((string) ($fields['message-headers'] ?? '[]'), true) as $pair) {
            if (is_array($pair) && count($pair) === 2) {
                $headers[strtolower((string) $pair[0])] = strtolower(trim((string) $pair[1]));
            }
        }

        if (isset($headers['auto-submitted']) && $headers['auto-submitted'] !== 'no') {
            return 'Marked as automatically generated (Auto-Submitted).';
        }
        if (isset($headers['x-auto-response-suppress']) || isset($headers['x-autoreply']) || isset($headers['x-autorespond'])) {
            return 'Looks like an automatic reply.';
        }
        if (in_array($headers['precedence'] ?? '', ['bulk', 'junk', 'list', 'auto_reply'], true)) {
            return 'Bulk or list mail (Precedence header).';
        }
        if (isset($headers['list-id'])) {
            return 'Mailing-list message.';
        }
        if (($headers['return-path'] ?? null) === '<>') {
            return 'Bounce message.';
        }

        $local = Str::before($fromEmail, '@');
        if (in_array($local, config('inbound_email.ignored_sender_locals'), true)) {
            return 'Sent from a system address.';
        }

        // Our own outgoing mail coming back round (a forwarding loop) must never become a ticket.
        $own = InboundEmailSettings::address($tenant);
        if ($own && $fromEmail === strtolower($own)) {
            return 'Sent from this workspace’s own inbound address (mail loop).';
        }

        return null;
    }
}
